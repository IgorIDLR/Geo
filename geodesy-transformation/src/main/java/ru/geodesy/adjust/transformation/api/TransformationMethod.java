package ru.geodesy.adjust.transformation.api;

/**
 * Метод трансформации координат.
 */
public enum TransformationMethod {

    /** 7-параметрическое преобразование Бурса-Вольфа. */
    HELMERT,

    /** 3-параметрическое преобразование Молоденского. */
    MOLODENSKY,

    /** Проекция Гаусса-Крюгера. */
    GAUSS_KRUGER,

    /** Произвольные EPSG-преобразования через Proj4J. */
    PROJ4J,

    /** По общим точкам (апостериорное определение параметров). */
    BY_POINTS,

    /** Без преобразования. */
    NONE
}